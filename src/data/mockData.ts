// Helper to generate slots for a facility
export function generateFacilitySlots(facilityId: string): ParkingSlot[] {
  const slots: ParkingSlot[] = [];
  const floors = ['Basement 1', 'Floor 1', 'Floor 2'];
  
  floors.forEach((floor, fIndex) => {
    const floorPrefix = fIndex === 0 ? 'B1' : fIndex === 1 ? 'F1' : 'F2';
    for (let i = 1; i <= 12; i++) {
      const isEv = i <= 2;
      const isHandicap = i === 3;
      const slotNum = `${floorPrefix}-${i < 10 ? '0' + i : i}`;
      let status: 'AVAILABLE' | 'OCCUPIED' | 'RESERVED' | 'MAINTENANCE' = 'AVAILABLE';
      
      // Deterministic spread
      if ((i + fIndex) % 3 === 0) status = 'OCCUPIED';
      else if ((i + fIndex) % 7 === 0) status = 'RESERVED';
      else if (i === 11 && fIndex === 2) status = 'MAINTENANCE';

      slots.push({
        id: `slot_${facilityId}_${slotNum}`,
        facilityId,
        slotNumber: slotNum,
        floor,
        type: isEv ? 'ev' : isHandicap ? 'handicap' : (i % 2 === 0 ? 'suv' : 'standard'),
        status,
        sensorId: `IOT_SNR_${facilityId.substring(4, 8).toUpperCase()}_${slotNum}`,
        lastUpdated: 'Just now',
      });
    }
  });

  return slots;
}

